/** SVG markup for an icon. size = rendered width in px. */
export function iconSVG(name, size = 96, { color } = {}) {
  const rows = ICONS[name];
  if (!rows) throw new Error('unknown icon: ' + name);
  const w = Math.max(...rows.map(r => r.length)), h = rows.length;
  let rects = '';
  rows.forEach((r, y) => [...r].forEach((ch, x) => { if (ch !== '.') rects += `<rect x="${x}" y="${y}" width="1.02" height="1.02" fill="${color && ch === '#' ? color : P[ch]}"/>`; }));
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${size}" height="${size * h / w}" shape-rendering="crispEdges">${rects}</svg>`;
}

export function iconEl(name, size, opts) {
  const d = document.createElement('div');
  d.style.lineHeight = '0';
  d.innerHTML = iconSVG(name, size, opts);
  return d;
}
